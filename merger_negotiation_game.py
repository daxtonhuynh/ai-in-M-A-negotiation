from __future__ import annotations

from dataclasses import dataclass, replace
from typing import Callable, Dict, List, Optional, Tuple
import math
import time

# ------------------------------------------------------------
# Type aliases
# ------------------------------------------------------------
Action = Tuple[str, Optional[float]]  # ('offer', price), ('accept', price), ('exit', None)


@dataclass(frozen=True)
class NegotiationState:
    """
    State representation for bilateral merger negotiation.

    This follows the standard adversarial-search game definition:
    - TO-MOVE(s): state.turn
    - ACTIONS(s): generated by game.actions(state)
    - RESULT(s, a): generated by game.result(state, action)
    - IS-TERMINAL(s): generated by game.is_terminal(state)
    - UTILITY(s): generated by game.utility(state)
    """

    turn: str  # 'buyer' or 'seller'
    round_no: int
    current_offer: Optional[float]

    buyer_reservation: float
    seller_reservation: float
    synergy: float
    delay_cost: float
    max_rounds: int

    buyer_remaining_concession: float
    seller_remaining_concession: float

    status: str = "ongoing"  # ongoing / accepted / buyer_exit / seller_exit / horizon
    agreed_price: Optional[float] = None
    last_buyer_offer: Optional[float] = None
    last_seller_offer: Optional[float] = None


class BilateralMergerNegotiation:
    """
    Deterministic, turn-taking, fully observable, finite-horizon bargaining game.

    Buyer is the MAX player.
    Seller is the MIN player.
    Utility is computed from the buyer / MAX perspective.

    exit_payoff_mode controls how no-deal exits are evaluated:
    - "asymmetric_relative" preserves the payoff logic used in the current draft/results.
      Under this relative zero-sum view, seller_exit can be positive for the buyer.
    - "symmetric_breakdown" treats any deal failure as a negative breakdown outcome
      for the buyer; this is often conceptually cleaner, but it will change the results.
    """

    def __init__(
        self,
        buyer_reservation: float,
        seller_reservation: float,
        synergy: float,
        delay_cost: float,
        buyer_concession_budget: float,
        seller_concession_budget: float,
        max_rounds: int,
        offer_step: float = 5.0,
        breakdown_penalty: float = 20.0,
        use_move_ordering: bool = True,
        exit_payoff_mode: str = "asymmetric_relative",
    ) -> None:
        if exit_payoff_mode not in {"asymmetric_relative", "symmetric_breakdown"}:
            raise ValueError("exit_payoff_mode must be 'asymmetric_relative' or 'symmetric_breakdown'.")

        numeric = (buyer_reservation, seller_reservation, synergy, delay_cost,
                   buyer_concession_budget, seller_concession_budget, offer_step, breakdown_penalty)
        if not all(math.isfinite(x) for x in numeric):
            raise ValueError("Parameters must be finite.")
        if offer_step <= 0 or max_rounds < 1 or not isinstance(max_rounds, int):
            raise ValueError("offer_step must be positive and max_rounds a positive integer.")
        if min(synergy, delay_cost, buyer_concession_budget, seller_concession_budget, breakdown_penalty) < 0:
            raise ValueError("Synergy, costs, budgets and penalty must be nonnegative.")
        if seller_reservation > buyer_reservation + synergy:
            raise ValueError("This model requires an overlapping feasible price zone.")
        self.offer_step = offer_step
        self.breakdown_penalty = breakdown_penalty
        self.use_move_ordering = use_move_ordering
        self.exit_payoff_mode = exit_payoff_mode

        self.initial_state = NegotiationState(
            turn="buyer",
            round_no=1,
            current_offer=None,
            buyer_reservation=buyer_reservation,
            seller_reservation=seller_reservation,
            synergy=synergy,
            delay_cost=delay_cost,
            max_rounds=max_rounds,
            buyer_remaining_concession=buyer_concession_budget,
            seller_remaining_concession=seller_concession_budget,
        )

    # --------------------------------------------------------
    # Core game definition
    # --------------------------------------------------------
    def to_move(self, state: NegotiationState) -> str:
        return state.turn

    def buyer_feasible_max(self, state: NegotiationState) -> float:
        # Buyer can justify paying up to standalone value + synergy.
        return state.buyer_reservation + state.synergy

    def seller_feasible_min(self, state: NegotiationState) -> float:
        return state.seller_reservation

    def is_terminal(self, state: NegotiationState) -> bool:
        return state.status != "ongoing" or state.round_no > state.max_rounds

    def _frange(self, start: float, stop: float, step: float) -> List[float]:
        values: List[float] = []
        x = start
        while x <= stop + 1e-9:
            values.append(round(x, 2))
            x += step
        return values

    def actions(self, state: NegotiationState) -> List[Action]:
        """
        Legal actions:
        - ('offer', price)
        - ('accept', current_offer)
        - ('exit', None)

        Buyer revises upward from a low-price aspiration.
        Seller revises downward from a high-price aspiration.
        Price is discretized by offer_step so the game tree is finite.
        """
        if self.is_terminal(state):
            return []

        actions: List[Action] = []

        # Acceptance rule: the responder may accept if the current offer lies in its feasible set.
        if state.current_offer is not None:
            if state.turn == "seller" and state.current_offer >= state.seller_reservation:
                actions.append(("accept", state.current_offer))
            elif state.turn == "buyer" and state.current_offer <= self.buyer_feasible_max(state):
                actions.append(("accept", state.current_offer))

        # Either side can walk away.
        actions.append(("exit", None))

        if state.turn == "buyer":
            anchor = state.seller_reservation
            lower = state.last_buyer_offer if state.last_buyer_offer is not None else anchor
            upper = min(lower + state.buyer_remaining_concession, self.buyer_feasible_max(state))
            if lower <= upper:
                for price in self._frange(lower, upper, self.offer_step):
                    actions.append(("offer", price))
        else:
            anchor = self.buyer_feasible_max(state)
            upper = state.last_seller_offer if state.last_seller_offer is not None else anchor
            lower = max(upper - state.seller_remaining_concession, state.seller_reservation)
            if lower <= upper:
                for price in self._frange(lower, upper, self.offer_step):
                    actions.append(("offer", price))

        # Remove duplicates while preserving order.
        actions = list(dict.fromkeys(actions))

        if self.use_move_ordering:
            # Move ordering: helps alpha-beta prune more branches.
            if state.turn == "buyer":
                actions.sort(
                    key=lambda action: (
                        0 if action[0] == "accept" else 1 if action[0] == "offer" else 2,
                        -(action[1] if action[1] is not None else -math.inf),
                    )
                )
            else:
                actions.sort(
                    key=lambda action: (
                        0 if action[0] == "accept" else 1 if action[0] == "offer" else 2,
                        (action[1] if action[1] is not None else math.inf),
                    )
                )
        return actions

    def result(self, state: NegotiationState, action: Action) -> NegotiationState:
        if action not in self.actions(state):
            raise ValueError("Action is not legal in this state.")
        kind, value = action

        if kind == "accept":
            if value is None:
                raise ValueError("Accept action requires a price.")
            return replace(state, status="accepted", agreed_price=value)

        if kind == "exit":
            return replace(state, status="buyer_exit" if state.turn == "buyer" else "seller_exit")

        if kind != "offer" or value is None:
            raise ValueError(f"Invalid action: {action}")

        if state.turn == "buyer":
            anchor = state.seller_reservation
            previous = state.last_buyer_offer if state.last_buyer_offer is not None else anchor
            used = max(0.0, value - previous)
            return replace(
                state,
                turn="seller",
                current_offer=value,
                last_buyer_offer=value,
                buyer_remaining_concession=max(0.0, state.buyer_remaining_concession - used),
            )

        anchor = self.buyer_feasible_max(state)
        previous = state.last_seller_offer if state.last_seller_offer is not None else anchor
        used = max(0.0, previous - value)
        return replace(
            state,
            turn="buyer",
            round_no=state.round_no + 1,
            current_offer=value,
            last_seller_offer=value,
            seller_remaining_concession=max(0.0, state.seller_remaining_concession - used),
        )

    def utility(self, state: NegotiationState) -> float:
        """
        Terminal utility from the buyer / MAX perspective.

        If deal accepted at price p:
            buyer_gain  = (buyer_reservation + synergy) - p
            seller_gain = p - seller_reservation
            utility     = buyer_gain - seller_gain - delay_penalty

        For no-deal outcomes:
            - "asymmetric_relative": preserves the current draft's relative-payoff logic.
            - "symmetric_breakdown": treats breakdown as negative for the buyer regardless of who exits.
        """
        if not self.is_terminal(state):
            raise ValueError("utility() can only be called on a terminal state.")

        delay_penalty = (min(state.round_no, state.max_rounds + 1) - 1) * state.delay_cost

        if state.status == "accepted" and state.agreed_price is not None:
            price = state.agreed_price
            buyer_gain = self.buyer_feasible_max(state) - price
            seller_gain = price - state.seller_reservation
            return (buyer_gain - seller_gain) - delay_penalty

        if self.exit_payoff_mode == "symmetric_breakdown":
            return -(self.breakdown_penalty + delay_penalty)

        # Preserved for backward compatibility with the current draft/results.
        if state.status == "buyer_exit":
            return -(self.breakdown_penalty + delay_penalty)
        if state.status == "seller_exit":
            return +(self.breakdown_penalty - delay_penalty)

        # Horizon reached without agreement.
        return -(self.breakdown_penalty / 2.0 + delay_penalty)

    # --------------------------------------------------------
    # Heuristic evaluation functions for cutoff search
    # --------------------------------------------------------
    def h1(self, state: NegotiationState) -> float:
        """
        Heuristic 1: spread / price-attractiveness proxy.

        This is intentionally simple and mostly price-driven. It is not an admissible
        heuristic in the A* sense; it is a cutoff evaluation function for game search.
        """
        feasible_low = self.seller_feasible_min(state)
        feasible_high = self.buyer_feasible_max(state)

        if state.current_offer is None:
            return feasible_high - feasible_low

        if state.current_offer < feasible_low:
            return -(feasible_low - state.current_offer)
        if state.current_offer > feasible_high:
            return -(state.current_offer - feasible_high)
        return feasible_high - state.current_offer

    def h2(self, state: NegotiationState) -> float:
        """Heuristic 2: h1 plus time penalty."""
        return self.h1(state) - (state.round_no - 1) * state.delay_cost

    def h3(self, state: NegotiationState) -> float:
        """Heuristic 3: h2 plus breakdown-risk penalty."""
        feasible_low = self.seller_feasible_min(state)
        feasible_high = self.buyer_feasible_max(state)

        # Unresolved bid-ask gap, including each party's initial aspiration.
        # This is a deterministic pressure proxy, not a probability of breakdown.
        bid = state.last_buyer_offer if state.last_buyer_offer is not None else feasible_low
        ask = state.last_seller_offer if state.last_seller_offer is not None else feasible_high
        gap_to_zone = max(0.0, ask - bid)

        remaining_total_concession = (
            state.buyer_remaining_concession + state.seller_remaining_concession
        )
        remaining_rounds = max(0, state.max_rounds - state.round_no + 1)

        risk = 0.0
        if gap_to_zone > remaining_total_concession:
            risk += self.breakdown_penalty
        if remaining_rounds <= 1 and gap_to_zone > 0:
            risk += self.breakdown_penalty / 2.0

        return self.h2(state) - risk


# ------------------------------------------------------------
# Search algorithms
# ------------------------------------------------------------
def minimax(game: BilateralMergerNegotiation, state: NegotiationState) -> Tuple[float, Optional[Action]]:
    if game.is_terminal(state):
        return game.utility(state), None

    if game.to_move(state) == "buyer":
        best_value = -math.inf
        best_action: Optional[Action] = None
        for action in game.actions(state):
            value, _ = minimax(game, game.result(state, action))
            if value > best_value:
                best_value, best_action = value, action
        return best_value, best_action

    best_value = math.inf
    best_action = None
    for action in game.actions(state):
        value, _ = minimax(game, game.result(state, action))
        if value < best_value:
            best_value, best_action = value, action
    return best_value, best_action


def alpha_beta(
    game: BilateralMergerNegotiation,
    state: NegotiationState,
    depth_limit: Optional[int] = None,
    eval_fn: Optional[Callable[[NegotiationState], float]] = None,
    alpha: float = -math.inf,
    beta: float = math.inf,
    stats: Optional[Dict[str, int]] = None,
) -> Tuple[float, Optional[Action]]:
    if stats is not None:
        stats["nodes"] = stats.get("nodes", 0) + 1

    if game.is_terminal(state):
        return game.utility(state), None

    if depth_limit == 0:
        if eval_fn is None:
            raise ValueError("eval_fn must be provided when depth_limit is used.")
        return eval_fn(state), None

    next_depth = None if depth_limit is None else depth_limit - 1
    actions = game.actions(state)

    if game.to_move(state) == "buyer":
        best_value = -math.inf
        best_action: Optional[Action] = None
        for idx, action in enumerate(actions):
            value, _ = alpha_beta(game, game.result(state, action), next_depth, eval_fn, alpha, beta, stats)
            if value > best_value:
                best_value, best_action = value, action
            alpha = max(alpha, best_value)
            if alpha >= beta:
                if stats is not None:
                    stats["cutoff_events"] = stats.get("cutoff_events", 0) + 1
                    stats["pruned_siblings"] = stats.get("pruned_siblings", 0) + max(0, len(actions) - idx - 1)
                break
        return best_value, best_action

    best_value = math.inf
    best_action = None
    for idx, action in enumerate(actions):
        value, _ = alpha_beta(game, game.result(state, action), next_depth, eval_fn, alpha, beta, stats)
        if value < best_value:
            best_value, best_action = value, action
        beta = min(beta, best_value)
        if alpha >= beta:
            if stats is not None:
                stats["cutoff_events"] = stats.get("cutoff_events", 0) + 1
                stats["pruned_siblings"] = stats.get("pruned_siblings", 0) + max(0, len(actions) - idx - 1)
            break
    return best_value, best_action


# ------------------------------------------------------------
# Utilities for running experiments / demos
# ------------------------------------------------------------
def solve_one_step(
    game: BilateralMergerNegotiation,
    state: NegotiationState,
    method: str = "alphabeta",
    depth_limit: Optional[int] = 3,
    heuristic: str = "h3",
) -> Tuple[float, Optional[Action], Dict[str, float]]:
    start = time.perf_counter()
    stats: Dict[str, float] = {"nodes": 0, "cutoff_events": 0, "pruned_siblings": 0}

    if method == "minimax":
        value, action = minimax(game, state)
    elif method == "alphabeta":
        value, action = alpha_beta(game, state, depth_limit=None, eval_fn=None, stats=stats)
    elif method == "heuristic_alphabeta":
        eval_fn = getattr(game, heuristic)
        value, action = alpha_beta(game, state, depth_limit=depth_limit, eval_fn=eval_fn, stats=stats)
    else:
        raise ValueError("method must be 'minimax', 'alphabeta', or 'heuristic_alphabeta'.")

    stats["runtime_sec"] = time.perf_counter() - start
    return value, action, stats
